import json
import os

import numpy as np
from PIL import Image
from scipy import ndimage

SRC = r"C:\Users\h7242\Desktop\道具素材\小黄鸭\hye-Zhengti.png"
OUT = r"E:\app\python\agent\deer-flow-mascot\public\parts"
MANIFEST = r"E:\app\python\agent\deer-flow-mascot\src\parts-manifest.ts"

os.makedirs(OUT, exist_ok=True)
im = Image.open(SRC).convert("RGBA")
a = np.array(im).astype(int)
pristine = a[:, :, :3].copy()
alpha = a[:, :, 3].copy()
solid = alpha > 16
lum = pristine.sum(axis=2)
dark = lum < 330
free = ndimage.binary_closing(solid & ~dark, np.ones((3, 3)))
labels, n = ndimage.label(free)

groups = {k: [] for k in ("hat", "body", "beak", "hand_l", "hand_r", "boot_l", "boot_r")}
for lab in range(1, n + 1):
    ys, xs = np.where(labels == lab)
    if len(xs) < 200:
        continue
    x0, y0, x1, y1 = int(xs.min()), int(ys.min()), int(xs.max()), int(ys.max())
    cx, cy = (x0 + x1) / 2, (y0 + y1) / 2
    if y1 < 600 and y0 < 300:
        groups["hat"].append(lab)
    elif 600 <= x0 and x1 <= 1060 and 580 <= y0 and y1 <= 790:
        groups["beak"].append(lab)
    elif y0 > 1100 and cx < 850:
        groups["boot_l"].append(lab)
    elif y0 > 1100:
        groups["boot_r"].append(lab)
    elif 780 <= cy <= 1060 and x1 < 430:
        groups["hand_l"].append(lab)
    elif 780 <= cy <= 1060 and x0 > 1190:
        groups["hand_r"].append(lab)
    else:
        groups["body"].append(lab)


def claim_dark(fm, reach):
    return fm | (dark & solid & ndimage.binary_dilation(fm, np.ones((reach, reach))))


masks = {name: claim_dark(np.isin(labels, labs), 31) for name, labs in groups.items() if labs}

bolt_gate = ((pristine[:, :, 1] - pristine[:, :, 2]) > 74) & solid


def piece_from_rect(rect, gate, reach=7):
    x0, y0, x1, y1 = rect
    m = np.zeros_like(solid)
    m[y0:y1, x0:x1] = True
    core = m & gate & solid
    return claim_dark(core, reach) & (m | ndimage.binary_dilation(m, np.ones((reach, reach))))


masks["bolt"] = piece_from_rect((795, 335, 1195, 485), bolt_gate)
eye_dark = dark & solid
masks["eye_l"] = piece_from_rect((560, 520, 672, 672), eye_dark)
masks["eye_r"] = piece_from_rect((1010, 520, 1122, 672), eye_dark)

others = np.zeros_like(solid)
for name, m in masks.items():
    if name != "body":
        others |= m
masks["body"] &= ~others

hole = ndimage.binary_fill_holes(masks["body"]) & ~masks["body"]
fill = None
if hole.any():
    ring = ndimage.binary_dilation(hole, np.ones((9, 9))) & masks["body"] & free
    fill = np.median(pristine[ring], axis=0).astype(int)

assigned = np.zeros_like(solid)
for m in masks.values():
    assigned |= m
un = solid & ~assigned
if un.any():
    _, (iy, ix) = ndimage.distance_transform_edt(~assigned, return_indices=True)
    owner = np.zeros(solid.shape, int)
    for idx, (name, m) in enumerate(masks.items(), 1):
        owner[m] = idx
    nearest = owner[iy, ix]
    for idx, name in enumerate(list(masks), 1):
        masks[name] |= un & (nearest == idx)
    print("reassigned unclaimed:", int(un.sum()))

manifest = {}
for name, m in masks.items():
    ys, xs = np.where(m)
    x0, y0, x1, y1 = int(xs.min()), int(ys.min()), int(xs.max()), int(ys.max())
    sub = m[y0 : y1 + 1, x0 : x1 + 1]
    crop_rgb = pristine[y0 : y1 + 1, x0 : x1 + 1].copy()
    if name == "body" and fill is not None:
        crop_rgb[hole[y0 : y1 + 1, x0 : x1 + 1]] = fill
    crop = np.zeros((y1 - y0 + 1, x1 - x0 + 1, 4), np.uint8)
    crop[sub] = np.concatenate([crop_rgb[sub], np.full((int(sub.sum()), 1), 255)], axis=1)
    fn = f"{name}.png"
    Image.fromarray(crop, "RGBA").save(os.path.join(OUT, fn))
    manifest[name] = {"file": fn, "x": x0, "y": y0, "w": x1 - x0 + 1, "h": y1 - y0 + 1}
    print(name, manifest[name])

with open(MANIFEST, "w", encoding="utf-8") as f:
    f.write("// generated by scripts/cut_cowboy.py\n")
    f.write("export type PartDef = { file: string; x: number; y: number; w: number; h: number };\n\n")
    f.write("export const PARTS: Record<string, PartDef> = ")
    f.write(json.dumps(manifest, indent=2, ensure_ascii=False))
    f.write(";\n")

canvas = np.zeros((1280, 1856, 4), np.uint8)
for name, info in manifest.items():
    piece = np.array(Image.open(os.path.join(OUT, info["file"])).convert("RGBA"))
    x0, y0 = info["x"], info["y"]
    sub = piece[:, :, 3] > 16
    tgt = canvas[y0 : y0 + info["h"], x0 : x0 + info["w"]]
    tgt[sub] = piece[sub]
    canvas[y0 : y0 + info["h"], x0 : x0 + info["w"]] = tgt
both = (canvas[:, :, 3] > 16) & (alpha > 16)
diff = (np.abs(canvas[:, :, :3].astype(int) - pristine).sum(axis=2) > 30) & both
missing = (alpha > 16) & (canvas[:, :, 3] <= 16)
print("reassembled diff vs source: %.4f%%  missing: %.4f%%" % (100 * diff.mean(), 100 * missing.mean()))
