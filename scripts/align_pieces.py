import json
import os

import numpy as np
from PIL import Image

BASE = r"C:\Users\h7242\Desktop\道具素材\小黄鸭"
STAGE = os.path.join(BASE, "0.hye-Zhengti.png")
OUTDIR = r"E:\app\python\agent\deer-flow-mascot\public\parts-user"
MANIFEST = r"E:\app\python\agent\deer-flow-mascot\src\parts-user-manifest.ts"

PIECES = [
    ("body", "1.hya-only-shenti_副本.png", [(93, 4, 1152, 1126)]),
    ("eye_0", "2.hya-yanjing.png", [(579, 519, 73, 124)]),
    ("eye_1", "2.hya-yanjing.png", [(1027, 520, 70, 119)]),
    ("beak", "3.hya-嘴巴.png", [(650, 602, 379, 143)]),
    ("hand_0", "4.hya-shou.png", [(172, 813, 232, 233)]),
    ("hand_1", "4.hya-shou.png", [(1221, 813, 233, 234)]),
    ("belt", "5.hya-腰带.png", [(438, 945, 745, 65)]),
    ("boot_l", "6.hya-zuojiao.png", [(477, 1124, 207, 148)]),
    ("boot_r", "7.hya-youjiao.png", [(930, 1124, 210, 147)]),
]

os.makedirs(OUTDIR, exist_ok=True)
stage = np.array(Image.open(STAGE).convert("RGBA")).astype(np.float64)
sg = 0.299 * stage[:, :, 0] + 0.587 * stage[:, :, 1] + 0.114 * stage[:, :, 2]
H, W = sg.shape


def crop_to_alpha(img):
    arr = np.array(img)
    ys, xs = np.where(arr[:, :, 3] > 16)
    return img.crop((int(xs.min()), int(ys.min()), int(xs.max()) + 1, int(ys.max()) + 1))


def mse_at(g, m, x, y):
    h, w = m.shape
    if x < 0 or y < 0 or x + w > W or y + h > H:
        return 1e18
    win = sg[y : y + h, x : x + w]
    d = (win - g)[m]
    return float((d * d).mean()) if d.size else 1e18


manifest = {}
report = {}
for name, fn, guesses in PIECES:
    src = Image.open(os.path.join(BASE, fn)).convert("RGBA")
    gx, gy, gw, gh = guesses[0]
    img = crop_to_alpha(src)
    pw, ph = img.size
    base_w, base_h = gw, gh
    best = None
    for f in np.arange(0.97, 1.0301, 0.005):
        nw, nh = max(4, int(round(base_w * f))), max(4, int(round(base_h * f)))
        rs = img.resize((nw, nh), Image.LANCZOS)
        arr = np.array(rs).astype(np.float64)
        m = arr[:, :, 3] > 127
        g = 0.299 * arr[:, :, 0] + 0.587 * arr[:, :, 1] + 0.114 * arr[:, :, 2]
        x0 = gx + (gw - nw) // 2
        y0 = gy + (gh - nh) // 2
        for dx in range(-8, 9, 2):
            for dy in range(-8, 9, 2):
                e = mse_at(g, m, x0 + dx, y0 + dy)
                if best is None or e < best[0]:
                    best = (e, float(f), x0 + dx, y0 + dy, nw, nh)
    e0, f0, bx, by, bw, bh = best
    rs = img.resize((bw, bh), Image.LANCZOS)
    arr = np.array(rs).astype(np.float64)
    m = arr[:, :, 3] > 127
    g = 0.299 * arr[:, :, 0] + 0.587 * arr[:, :, 1] + 0.114 * arr[:, :, 2]
    for dx in range(-2, 3):
        for dy in range(-2, 3):
            e = mse_at(g, m, bx + dx, by + dy)
            if e < best[0]:
                best = (e, f0, bx + dx, by + dy, bw, bh)
    e, f, x, y, nw, nh = best
    manifest[name] = {"file": fn, "x": x, "y": y, "w": nw, "h": nh}
    report[name] = (e, f, x, y)
    img.resize((nw, nh), Image.LANCZOS).save(os.path.join(OUTDIR, f"{name}.png"))
    print(f"{name}: s={f:.3f} @{x},{y} {nw}x{nh} mse={e:.1f}")

with open(MANIFEST, "w", encoding="utf-8") as f:
    f.write("// generated by scripts/align_pieces.py (exact replica of 0.hye-Zhengti)\n")
    f.write("export type PartDef = { file: string; x: number; y: number; w: number; h: number };\n\n")
    f.write("export const PARTS_USER: Record<string, PartDef> = ")
    f.write(json.dumps(manifest, indent=2, ensure_ascii=False))
    f.write(";\n")

canvas = np.zeros((H, W, 4), np.uint8)
order = ["boot_l", "boot_r", "body", "belt", "eye_0", "eye_1", "beak", "hand_0", "hand_1"]
for tag in order:
    info = manifest[tag]
    piece = np.array(Image.open(os.path.join(OUTDIR, f"{tag}.png")).convert("RGBA"))
    x, y = info["x"], info["y"]
    hgt, wid = piece.shape[:2]
    sub = piece[:, :, 3] > 16
    tgt = canvas[y : y + hgt, x : x + wid]
    tgt[sub] = piece[sub]
    canvas[y : y + hgt, x : x + wid] = tgt
both = (canvas[:, :, 3] > 16) & (stage[:, :, 3] > 16)
d = np.abs(canvas[:, :, :3] - stage[:, :, :3]).sum(axis=2)
for thr in (30, 60, 120):
    diff = (d > thr) & both
    print("composite diff >%d: %.3f%%" % (thr, 100 * diff.mean()))
missing = (stage[:, :, 3] > 16) & (canvas[:, :, 3] <= 16)
print("missing: %.3f%%" % (100 * missing.mean()))
