import json
import os

import numpy as np
from PIL import Image
from scipy import ndimage

BASE = r"C:\Users\h7242\Desktop\道具素材\小黄鸭的马"
STAGE = os.path.join(BASE, "0.ma-zhengti.png")
OUTDIR = r"E:\app\python\agent\deer-flow-mascot\public\parts-horse"
MANIFEST = r"E:\app\python\agent\deer-flow-mascot\src\horse-manifest.ts"

os.makedirs(OUTDIR, exist_ok=True)
stage = np.array(Image.open(STAGE).convert("RGBA")).astype(np.float64)
sg = 0.299 * stage[:, :, 0] + 0.587 * stage[:, :, 1] + 0.114 * stage[:, :, 2]
sa = stage[:, :, 3] > 16
H, W = sg.shape


def crop_to_alpha(img):
    arr = np.array(img)
    ys, xs = np.where(arr[:, :, 3] > 16)
    return img.crop((int(xs.min()), int(ys.min()), int(xs.max()) + 1, int(ys.max()) + 1))


def mse_at(g, m, x, y):
    h, w = m.shape
    if x < 0 or y < 0 or x + w > W or y + h > H:
        return 1e18
    win = sg[y : y + h, x : x + w]
    d = (win - g)[m]
    return float((d * d).mean()) if d.size else 1e18


def refine(img, guess, s_range=(0.95, 1.051, 0.01), o=15):
    img = crop_to_alpha(img)
    pw, ph = img.size
    gx, gy, gw, gh = guess
    best = None
    for f in np.arange(*s_range):
        nw, nh = max(4, int(round(gw * f))), max(4, int(round(gh * f)))
        rs = img.resize((nw, nh), Image.LANCZOS)
        arr = np.array(rs).astype(np.float64)
        m = arr[:, :, 3] > 127
        g = 0.299 * arr[:, :, 0] + 0.587 * arr[:, :, 1] + 0.114 * arr[:, :, 2]
        x0 = gx + (gw - nw) // 2
        y0 = gy + (gh - nh) // 2
        for dx in range(-o, o + 1, 3):
            for dy in range(-o, o + 1, 3):
                e = mse_at(g, m, x0 + dx, y0 + dy)
                if best is None or e < best[0]:
                    best = (e, float(f), x0 + dx, y0 + dy, nw, nh)
    e0, f0, bx, by, bw, bh = best
    rs = img.resize((bw, bh), Image.LANCZOS)
    arr = np.array(rs).astype(np.float64)
    m = arr[:, :, 3] > 127
    g = 0.299 * arr[:, :, 0] + 0.587 * arr[:, :, 1] + 0.114 * arr[:, :, 2]
    for dx in range(-2, 3):
        for dy in range(-2, 3):
            e = mse_at(g, m, bx + dx, by + dy)
            if e < best[0]:
                best = (e, f0, bx + dx, by + dy, bw, bh)
    return best


body_img = Image.open(os.path.join(BASE, "1.ma-zhuti.png")).convert("RGBA")
b_arr = np.array(body_img)
bys, bxs = np.where(b_arr[:, :, 3] > 16)
b_box = (int(bxs.min()), int(bys.min()), int(bxs.max()) - int(bxs.min()) + 1, int(bys.max()) - int(bys.min()) + 1)
print("body content bbox in its canvas:", b_box)
e, f, x, y, nw, nh = refine(body_img, b_box, s_range=(0.98, 1.021, 0.01), o=12)
print(f"body: s={f:.3f} @{x},{y} {nw}x{nh} mse={e:.1f}")
manifest = {"body": {"file": "1.ma-zhuti.png", "x": x, "y": y, "w": nw, "h": nh}}
body_rgba = np.zeros((H, W, 4), np.uint8)
bp = np.array(crop_to_alpha(body_img).resize((nw, nh), Image.LANCZOS))
ys, xs = np.where(bp[:, :, 3] > 16)
body_rgba[y + ys, x + xs] = bp[ys, xs]
body_rgba[:, :, 3] = np.where(body_rgba[:, :, 3] > 16, 255, 0)

uncovered = sa & (body_rgba[:, :, 3] <= 16)
print("uncovered px:", int(uncovered.sum()))
lab, n = ndimage.label(uncovered)
sizes = ndimage.sum(uncovered, lab, range(1, n + 1))
regions = []
for i in np.argsort(-sizes):
    if sizes[i] < 3000:
        break
    ys, xs = np.where(lab == i + 1)
    regions.append((int(xs.min()), int(ys.min()), int(xs.max()) - int(xs.min()) + 1, int(ys.max()) - int(ys.min()) + 1))
print("leg regions:", len(regions))
for r in regions:
    print("  region", r)

leg_img = Image.open(os.path.join(BASE, "3.ma-duantui.png")).convert("RGBA")
for k, (rx, ry, rw, rh) in enumerate(regions):
    e, f, x, y, nw, nh = refine(leg_img, (rx, ry, rw, rh), s_range=(0.5, 1.61, 0.05), o=18)
    tag = f"leg_{k}"
    print(f"{tag}: s={f:.3f} @{x},{y} {nw}x{nh} mse={e:.1f}")
    manifest[tag] = {"file": "3.ma-duantui.png", "x": x, "y": y, "w": nw, "h": nh}

for tag, info in manifest.items():
    src = Image.open(os.path.join(BASE, info["file"])).convert("RGBA")
    crop_to_alpha(src).resize((info["w"], info["h"]), Image.LANCZOS).save(os.path.join(OUTDIR, f"{tag}.png"))

with open(MANIFEST, "w", encoding="utf-8") as f:
    f.write("// generated by scripts/align_horse.py (exact replica of 0.ma-zhengti)\n")
    f.write("export type PartDef = { file: string; x: number; y: number; w: number; h: number };\n\n")
    f.write("export const PARTS_HORSE: Record<string, PartDef> = ")
    f.write(json.dumps(manifest, indent=2, ensure_ascii=False))
    f.write(";\n")

canvas = np.zeros((H, W, 4), np.uint8)
